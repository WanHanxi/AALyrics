#!/usr/bin/env python3
"""Regenerate comparison-only Unicode tables with ICU 78.3 uconv (Unicode-3.0).

Single-code-point mappings intentionally omit contextual word transliteration.
These tables are comparison variants, never displayed text or identity proof.
"""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'provider/matching/src/main/resources/io/github/whoxamxl/aalyrics/provider/matching'
OUT.mkdir(parents=True, exist_ok=True)
for filename, ranges, transform in [
    ('han-folds.tsv', [(0x3400, 0xA000), (0xF900, 0xFB00)], 'Traditional-Simplified'),
    ('cyrillic-folds.tsv', [(0x400, 0x530)], 'Cyrillic-Latin; Latin-ASCII'),
]:
    chars = [chr(i) for start, end in ranges for i in range(start, end)]
    converted = subprocess.check_output(['uconv', '-x', transform], input='\n'.join(chars), text=True).split('\n')
    assert len(chars) == len(converted)
    pairs = [f'{ord(a):04X}\t{b}' for a, b in zip(chars, converted) if a != b]
    (OUT / filename).write_text('# ICU 78.3; Unicode-3.0; generated by scripts/generate-match-folds.py\n' + '\n'.join(pairs) + '\n')
    print(filename, len(pairs))
